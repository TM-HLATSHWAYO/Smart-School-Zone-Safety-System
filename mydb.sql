-- Create the database
CREATE DATABASE IF NOT EXISTS Group_12;
USE Group_12;

-- User registration table
CREATE TABLE IF NOT EXISTS Registration (
    id INT AUTO_INCREMENT PRIMARY KEY,
    Username VARCHAR(100) NOT NULL UNIQUE,
    User_Password VARCHAR(255) NOT NULL,
    Student_Email VARCHAR(255) NOT NULL UNIQUE
);

-- Humidity sensor table
CREATE TABLE IF NOT EXISTS humidity (
    id INT AUTO_INCREMENT PRIMARY KEY,
    relative_humidity FLOAT NOT NULL,
    lastUpdated TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- Temperature sensor table
CREATE TABLE IF NOT EXISTS temperature (
    id INT AUTO_INCREMENT PRIMARY KEY,
    temp_value FLOAT NOT NULL,
    lastUpdated TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- Ultrasonic sensor table
CREATE TABLE IF NOT EXISTS ultrasonic (
    id INT AUTO_INCREMENT PRIMARY KEY,
    altra_value FLOAT NOT NULL,
    lastUpdated TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- PIR sensor table
CREATE TABLE IF NOT EXISTS pir (
    id INT AUTO_INCREMENT PRIMARY KEY,
    PIR_STATUS VARCHAR(50) NOT NULL,
    lastUpdated TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- LDR sensor table
CREATE TABLE IF NOT EXISTS ldr_1 (
    id INT AUTO_INCREMENT PRIMARY KEY,
    Ldr_1_data FLOAT NOT NULL,
    lastUpdated TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
